-- ============================================================================
-- BLOCO 1  ·  AS TABELAS
-- ============================================================================
-- Aqui a gente cria as seis gavetas onde tudo vai ficar guardado.
-- "if not exists" quer dizer: so cria se ainda nao existir.
-- Todas tem um "id" que o banco gera sozinho e um "criado_em" com a data.

-- Os seus videos, que alimentam a tabela da aba Portfolio
create table if not exists public.videos (
  id          bigint generated by default as identity primary key,
  titulo      text not null default '',
  link        text not null default '',
  nicho       text default '',
  formato     text default '',
  marca       text default '',
  destaque    text default '',          -- texto livre, ex: 2,4M views
  ordem       integer not null default 0,
  visivel     boolean not null default true,
  criado_em   timestamptz not null default now()
);

-- A sua base de contatos de empresa, que alimenta a aba Marcas
create table if not exists public.marcas (
  id              bigint generated by default as identity primary key,
  nome            text not null default '',
  instagram       text default '',
  email           text default '',
  telefone        text default '',
  situacao        text not null default 'lead',   -- lead, conversando, cliente, parada
  obs             text default '',
  ultimo_contato  date,
  criado_em       timestamptz not null default now()
);

-- Os seus compromissos de gravar, editar e postar, que alimentam a aba Calendario
create table if not exists public.calendario (
  id          bigint generated by default as identity primary key,
  titulo      text not null default '',
  marca       text default '',
  tipo        text not null default 'gravar',   -- gravar, editar, postar
  data        date not null default current_date,
  status      text not null default 'a fazer',  -- a fazer, feito
  criado_em   timestamptz not null default now()
);

-- Os seus trabalhos fechados, que alimentam a aba Campanhas
create table if not exists public.campanhas (
  id          bigint generated by default as identity primary key,
  campanha    text not null default '',
  cliente     text default '',
  tipo        text not null default 'Conteúdo',   -- Conteúdo ou Publicidade
  status      text not null default 'Briefing',   -- Briefing, Roteiro, Aprovação Roteiro, Gravação, Edição, Aprovado, Entregue
  qtd         integer not null default 1,
  valor       numeric(12,2) not null default 0,
  prazo       date,
  pagamento   text not null default 'pendente',   -- pendente ou pago
  ativa       boolean not null default true,
  favorita    boolean not null default false,
  criado_em   timestamptz not null default now()
);

-- O que voce ja marcou no checklist do portfolio.
-- Cada coisa marcada vira UMA linha, identificada por uma chave de texto.
-- A chave nao pode repetir, por isso o "unique".
create table if not exists public.marcados (
  id          bigint generated by default as identity primary key,
  chave       text not null unique,
  criado_em   timestamptz not null default now()
);

-- O registro de quem visitou o seu site, que alimenta os numeros da aba Portfolio.
-- Comeca vazia de proposito. Nenhuma visita inventada.
create table if not exists public.visitas (
  id          bigint generated by default as identity primary key,
  data        date not null default current_date,
  pagina      text default '/',
  origem      text default 'direto',
  criado_em   timestamptz not null default now()
);


-- ============================================================================
-- BLOCO 2  ·  CONSERTOS PARA QUEM JA RODOU UMA VERSAO ANTIGA
-- ============================================================================
-- Se as tabelas ja existiam sem algum campo, estas linhas acrescentam o que falta.
-- Se estiver tudo certo, elas nao fazem nada. Pode deixar.

alter table public.videos     add column if not exists destaque   text default '';
alter table public.videos     add column if not exists ordem      integer not null default 0;
alter table public.videos     add column if not exists visivel    boolean not null default true;
alter table public.marcas     add column if not exists obs        text default '';
alter table public.marcas     add column if not exists ultimo_contato date;
alter table public.campanhas  add column if not exists favorita   boolean not null default false;
alter table public.campanhas  add column if not exists ativa      boolean not null default true;
alter table public.campanhas  add column if not exists pagamento  text not null default 'pendente';
alter table public.visitas    add column if not exists origem     text default 'direto';


-- ============================================================================
-- BLOCO 3  ·  INDICES, PARA O PAINEL ABRIR RAPIDO
-- ============================================================================
-- Indice e como o indice de um livro: o banco acha a informacao sem ler tudo.

create index if not exists videos_ordem_idx      on public.videos (ordem);
create index if not exists marcas_situacao_idx   on public.marcas (situacao);
create index if not exists calendario_data_idx   on public.calendario (data);
create index if not exists campanhas_prazo_idx   on public.campanhas (prazo);
create index if not exists visitas_data_idx      on public.visitas (data);


-- ============================================================================
-- BLOCO 4  ·  A TRANCA  (RLS, Row Level Security)
-- ============================================================================
-- Isto e a parte mais importante do arquivo. NAO APAGUE.
--
-- Ligar o RLS numa tabela significa: por padrao, NINGUEM pode fazer nada.
-- Depois disso, so passa quem tiver uma permissao escrita explicitamente.
-- Como a chave publica do seu site fica visivel para qualquer pessoa,
-- e o RLS que impede um estranho de ler a sua base de marcas e de campanhas.

alter table public.videos     enable row level security;
alter table public.marcas     enable row level security;
alter table public.calendario enable row level security;
alter table public.campanhas  enable row level security;
alter table public.marcados   enable row level security;
alter table public.visitas    enable row level security;

-- Garantia extra: nem o dono da tabela escapa da tranca.
alter table public.videos     force row level security;
alter table public.marcas     force row level security;
alter table public.calendario force row level security;
alter table public.campanhas  force row level security;
alter table public.marcados   force row level security;
alter table public.visitas    force row level security;


-- ============================================================================
-- BLOCO 5  ·  AS PERMISSOES
-- ============================================================================
-- Primeiro a gente apaga qualquer permissao antiga com o mesmo nome,
-- para este arquivo poder ser rodado mais de uma vez sem dar erro.

drop policy if exists "logada faz tudo em videos"     on public.videos;
drop policy if exists "logada faz tudo em marcas"     on public.marcas;
drop policy if exists "logada faz tudo em calendario" on public.calendario;
drop policy if exists "logada faz tudo em campanhas"  on public.campanhas;
drop policy if exists "logada faz tudo em marcados"   on public.marcados;
drop policy if exists "logada faz tudo em visitas"    on public.visitas;
drop policy if exists "visitante pode virar lead"     on public.marcas;
drop policy if exists "visitante pode registrar visita" on public.visitas;

-- ----------------------------------------------------------------------------
-- 5.1  Voce, logada, faz tudo em todas as tabelas
-- ----------------------------------------------------------------------------
-- "to authenticated" quer dizer: so vale para quem entrou com e-mail e senha.
-- "using (true)" libera a leitura e "with check (true)" libera a escrita.
-- Quem nao esta logado nao aparece aqui, ou seja: nao le e nao escreve nada.
--
-- ATENCAO, um passo seu no painel do Supabase:
-- va em Authentication, depois Sign In / Providers, e DESLIGUE
-- "Allow new users to sign up". Sem isso, um estranho poderia criar uma
-- conta no seu projeto e essa conta passaria por estas permissoes.
-- Com a criacao de conta desligada, a unica usuaria logada possivel e voce.

create policy "logada faz tudo em videos" on public.videos
  for all to authenticated using (true) with check (true);

create policy "logada faz tudo em marcas" on public.marcas
  for all to authenticated using (true) with check (true);

create policy "logada faz tudo em calendario" on public.calendario
  for all to authenticated using (true) with check (true);

create policy "logada faz tudo em campanhas" on public.campanhas
  for all to authenticated using (true) with check (true);

create policy "logada faz tudo em marcados" on public.marcados
  for all to authenticated using (true) with check (true);

create policy "logada faz tudo em visitas" on public.visitas
  for all to authenticated using (true) with check (true);

-- ----------------------------------------------------------------------------
-- 5.2  PRIMEIRA EXCECAO  ·  qualquer pessoa pode se cadastrar como Lead
-- ----------------------------------------------------------------------------
-- E so INSERT, nunca SELECT. Um visitante consegue deixar o contato dele,
-- e nao consegue ler nem uma linha da sua base.
-- O "with check" obriga a situacao a entrar como 'lead': assim ninguem
-- pode se cadastrar fingindo ser seu cliente.

create policy "visitante pode virar lead" on public.marcas
  for insert to anon
  with check (situacao = 'lead');

-- ----------------------------------------------------------------------------
-- 5.3  SEGUNDA EXCECAO  ·  qualquer pessoa pode registrar uma visita
-- ----------------------------------------------------------------------------
-- Tambem so INSERT. O visitante grava que passou por ali,
-- e nao consegue ver quantas visitas voce teve. Ler, so voce.

create policy "visitante pode registrar visita" on public.visitas
  for insert to anon
  with check (true);

-- Nao existe mais nenhuma outra excecao. Em videos, calendario, campanhas
-- e marcados, quem nao esta logado nao faz absolutamente nada.


